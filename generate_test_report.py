"""Run every test case and write docs/TEST_REPORT.md with expected vs actual results.

Run from the repository root:   python -m tests.generate_test_report
"""

import io
import os
import platform
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from tests import cases

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "docs", "TEST_REPORT.md")

WORKINGS = {
    "TC-01": "45 + 85 + 146 + 85 + 108 + 110 + 59 + 2 = 640",
    "TC-02": "12 + 2 + 30 + 23 + 84 + 24 + 2 + 59 = 236",
    "TC-03": "16 + 23 + 14 + 65 + 2 + 31 + 24 + 2 + 59 = 236",
    "TC-04": "12 + 2 + 31 + 24 + 2 + 59 + 16 + 162 + 23 = 331",
    "TC-05": "32 + 88 + 127 + 97 + 116 + 8 + 174 = 642",
    "TC-06": "7 + 19 + 8 + 66 + 58 + 30 + 20 = 208",
    "TC-07": "7 + 19 + 8 + 16 + 82 + 58 + 30 + 20 = 240",
    "TC-08": "32 + 58 + 30 + 20 + 9 + 156 + 19 + 8 = 332",
    "TC-09": "Head is already at cylinder 0, so no boundary stop is added: 10 + 10 = 20",
    "TC-10": "All distances are 0: 0 + 0 = 0",
    "TC-11": "Nothing is behind the head, so no boundary stop is added: 10 + 30 = 40",
    "TC-12": "40 and 60 are both 10 away; the earlier request (40) goes first: 10 + 20 = 30",
}


def table(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |")
    return "\n".join(out)


def verdict(ok):
    return "PASS" if ok else "FAIL"


def main():
    passed = failed = 0

    algo_rows = []
    for case in cases.ALGORITHM_CASES:
        result = cases.run_algorithm_case(case)
        ok = (result["sequence"] == case["expected_sequence"]
              and result["total"] == case["expected_total"])
        passed, failed = passed + ok, failed + (not ok)
        inputs = (f"{case['algorithm']}, head {case['head']}, queue {', '.join(map(str, case['queue']))}, "
                  f"disk {case['min']}-{case['max']}"
                  + (f", {case['direction']}" if case["algorithm"] == "SCAN" else ""))
        expected = f"{' → '.join(map(str, case['expected_sequence']))} (total {case['expected_total']})"
        actual = f"{' → '.join(map(str, result['sequence']))} (total {result['total']})"
        algo_rows.append((case["id"], case["title"], inputs, expected, actual, verdict(ok)))

    val_rows = []
    for case in cases.VALIDATION_CASES:
        actual = cases.run_validation_case(case)
        ok = actual == case["expected_error"]
        passed, failed = passed + ok, failed + (not ok)
        inputs = (f"head {case['head']}, queue {case['queue']}, min {case['min']}, "
                  f"max {case['max']}, direction {case['direction']}")
        val_rows.append((case["id"], case["title"], inputs, case["expected_error"], actual, verdict(ok)))

    stream = io.StringIO()
    suite = unittest.defaultTestLoader.discover(os.path.join(ROOT, "tests"), top_level_dir=ROOT)
    unittest.TextTestRunner(stream=stream, verbosity=2).run(suite)

    total = passed + failed
    lines = [
        "# Test Report - Track Attack",
        "",
        f"**Result: {passed} of {total} automated test cases passed"
        + ("." if not failed else f", {failed} failed.") + "**",
        "",
        f"Environment: Python {platform.python_version()} on {platform.system()}. "
        "This file is generated by `python -m tests.generate_test_report`; re-running it refreshes "
        "the *Actual* columns.",
        "",
        "## How the tests were designed",
        "",
        "- The **expected** values were calculated by hand, one cylinder-to-cylinder distance at a time, "
        "before running the program. They are not copied from the program's output.",
        "- The textbook example (head 53, queue 98, 183, 37, 122, 14, 124, 65, 67) comes from the course "
        "slide, which states a total of 640 cylinders for FCFS.",
        "- **Actual** is what the program returned when the test ran.",
        "",
        "## 1. Algorithm test cases",
        "",
        table(algo_rows, ["ID", "Test case", "Input", "Expected", "Actual", "Result"]),
        "",
        "### Hand calculations for the expected totals",
        "",
        table(list(WORKINGS.items()), ["ID", "Working"]),
        "",
        "## 2. Input validation test cases",
        "",
        table(val_rows, ["ID", "Test case", "Input", "Expected message", "Actual message", "Result"]),
        "",
        "## 3. Unit test run",
        "",
        "Command: `python -m unittest discover -s tests -t . -v`",
        "",
        "```",
        stream.getvalue().strip(),
        "```",
        "",
        "## 4. Interface (GUI) test cases",
        "",
        "The window needs a screen, so these cases are run by hand and recorded in "
        "[MANUAL_TESTS.md](MANUAL_TESTS.md), with screenshots in `docs/screenshots/`.",
        "",
    ]

    with open(OUTPUT, "w", encoding="utf-8") as file:
        file.write("\n".join(lines))

    print(f"{passed}/{total} passed. Report written to {OUTPUT}")
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
